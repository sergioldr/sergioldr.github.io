export const textWidth = (s: string): number => s.length * 4 - 1;

export function text(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string): void {
  ctx.fillStyle = color;
  [...s.toUpperCase()].forEach((ch, k) => {
    (GLYPHS[ch] ?? []).forEach((row, j) => [...row].forEach((p, i) => {
      if (p === '#') ctx.fillRect(x + k * 4 + i, y + j, 1, 1);
    }));
  });
}
